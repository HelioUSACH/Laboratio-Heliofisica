Import("env")

import os

try:
    import yaml
except ImportError:
    env.Execute('"$PYTHONEXE" -m pip install pyyaml')
    import yaml

project_dir = env.subst("$PROJECT_DIR")
include_dir = env.subst("$PROJECT_INCLUDE_DIR")

config_file = os.path.join(project_dir, "config", "config.yaml")
header_file = os.path.join(include_dir, "config_gen.h")

with open(config_file, "r") as f:
    cfg = yaml.safe_load(f)

cc = cfg["cycle_count"]
address = cfg["RM3100_address"]
monitor_speed = cfg["serial_config"]["monitor_speed"]

# Value validation
if type(cc) is not int or not (0 <= cc <= 0xFFFF):
    raise ValueError(f"Cycle Count out of range (0..65535): {cc!r}")
if type(address) is not int or address not in (0x20, 0x21, 0x22, 0x23):
    raise ValueError(f"RM3100_address invalid: {address!r}")
if type(monitor_speed) is not int or monitor_speed <= 0:
    raise ValueError(f"monitor_speed invalid: {monitor_speed!r}")

content = (
    "#pragma once\n"
    "// Generated by python/config/gen_config.py from config/config.yaml: do not edit manually\n"
    f"#define RM3100Address 0x{address:02X}\n"
    f"#define initialCC {cc}\n"
    f"#define monitorSpeed {monitor_speed}\n"
)

os.makedirs(include_dir, exist_ok = True)

old = None
if os.path.exists(header_file):
    with open(header_file, "r") as f:
        old = f.read()

# Only rewrite if it changed, to avoid recompiling on every build
if content != old:
    with open(header_file, "w") as f:
        f.write(content)

    print(f"config_gen.h: RM3100Address=0x{address:02X}, initialCC={cc}, monitorSpeed={monitor_speed}")